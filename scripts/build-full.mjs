// npm run db:build, rebuilds dokankhata_full.sql from schema.sql + seed.sql.
// run it every time you change either of those
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dbDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'db', 'database');
const schema = readFileSync(join(dbDir, 'schema.sql'), 'utf8');
const seed = readFileSync(join(dbDir, 'seed.sql'), 'utf8');

const count = (re) => (schema.match(re) || []).length;
const tables = count(/^CREATE TABLE /gm);
const views = count(/^CREATE VIEW /gm);
const procs = count(/^CREATE PROCEDURE /gm);
const triggers = count(/^CREATE TRIGGER /gm);
const events = count(/^CREATE EVENT /gm);

const header = `-- =====================================================================
--  DokanKhata: complete database in ONE file (schema.sql + seed.sql)
--  GENERATED by scripts/build-full.mjs. Do not edit by hand.
--
--  XAMPP: start Apache and MySQL > open http://localhost/phpmyadmin >
--         click "Import" at the top WITHOUT selecting a database >
--         choose this file > Go.     (or: npm run db:reset)
--  It drops and rebuilds the \`dokankhata\` database: ${tables} tables, ${views} views,
--  ${procs} procedures, ${triggers} triggers, ${events} events, then loads the sample data.
--  Every demo login uses the password  dokan123
-- =====================================================================

`;

const out = header + schema.replace(/\s*$/, '\n') + '\n' + seed;
writeFileSync(join(dbDir, 'dokankhata_full.sql'), out);
console.log(
  `dokankhata_full.sql rebuilt: ${tables} tables, ${views} views, ${procs} procedures, ${triggers} triggers, ${events} events`,
);
